package com.wanderwildwood.jimeikin.ui

import com.wanderwildwood.jimeikin.BuildConfig
import java.io.File
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * The Licenses page's data as the build made it: the AboutLibraries plugin writes
 * build/generated/aboutLibraries/<variant>/res/raw/aboutlibraries.json before the unit tests
 * compile (it is part of the merged resources the R class comes from).
 */
class LicencesTest {
    // Two editions, two lists: each variant's tests read their own (Music Box K has no YouTube parts).
    private val variant = BuildConfig.FLAVOR + BuildConfig.BUILD_TYPE.replaceFirstChar { it.uppercase() }
    private val json: File? = File("build/generated/aboutLibraries").walkTopDown()
        .filter { it.name == "aboutlibraries.json" && "/$variant/" in it.path }
        .firstOrNull()

    private val generated by lazy { licenceComponentsFromJson(json!!.readText()) }

    private val data by lazy {
        LicencesData(
            "Music Box", SOURCE_URL, "GPL-3.0-only", generated,
            LICENCE_RAW.map { LicenceText(it.first, it.first, it.second) }, emptyList(),
        )
    }

    /** What must be on the page whatever else changes: group:artifact, or a config/libraries name. */
    private val EXPECTED = listOf(
        "com.google.guava:guava", "com.squareup.okhttp3:okhttp", "com.squareup.okio:okio",
        "androidx.media3:media3-exoplayer", "androidx.room:room-runtime", "com.mudita:MMD",
        "net.jthink:jaudiotagger", "org.jetbrains.kotlinx:kotlinx-coroutines-core",
        "Lato typeface", "Material Symbols icons", "CalmMusic (this app is a fork)",
        "Java library desugaring (desugar_jdk_libs)", "Public Suffix List",
    ) + if (BuildConfig.FLAVOR == "full") listOf(
        "com.github.TeamNewPipe:NewPipeExtractor", "com.github.TeamNewPipe:nanojson",
        "org.jsoup:jsoup", "org.mozilla:rhino", "org.mozilla:rhino-engine",
    ) else emptyList()

    @Test fun mmdIsMuditas() {
        assertEquals("Mudita", generated.first { it.note?.startsWith("com.mudita:MMD ") == true }.author)
    }

    @Test fun onlyWhatTheReleaseCarries() {
        val debugOnly = listOf("androidx.compose.ui:ui-tooling", "androidx.compose.ui:ui-tooling-data",
            "androidx.compose.ui:ui-test-manifest", "androidx.compose.material:material")
        assertEquals(emptyList<String>(), generated.mapNotNull { it.note?.substringBefore(' ') }.filter { it in debugOnly })
    }

    @Test fun musicBoxKListsNothingOfYouTube() {
        if (BuildConfig.FLAVOR != "store") return
        assertTrue(json!!.readText().let { !Regex("youtube|newpipe|schabi", RegexOption.IGNORE_CASE).containsMatchIn(it) })
    }

    @Test fun theBuildListedTheLibraries() {
        assertNotNull("no generated aboutlibraries.json: is the AboutLibraries plugin applied?", json)
        assertTrue(generated.size >= 5)
    }

    @Test fun theDataHasNoProblems() {
        assertEquals(emptyList<String>(), licencesProblems(data))
    }

    @Test fun everyExpectedComponentIsListed() {
        val missing = EXPECTED.filterNot { id -> generated.any { it.note?.startsWith("$id ") == true || it.name == id } }
        assertEquals(emptyList<String>(), missing)
    }

    @Test fun theSourceLinkIsTheRepo() {
        assertEquals("https://github.com/wanderwildwood/jimeikin", SOURCE_URL)
    }

    @Test fun gplIsFirstAndEveryTextIsBundled() {
        assertEquals("gpl", orderedTexts(data.texts).first().id)
        val raw = File("src/main/res/raw")
        assertTrue(raw.listFiles().orEmpty().count { it.extension == "txt" } >= LICENCE_RAW.size)
        assertTrue(licenceParagraphs(File(raw, raw.list().orEmpty().first { it.contains("gpl") }).readText()).size > 10)
    }
}
